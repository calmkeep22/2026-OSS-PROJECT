"""
한국어 금융 감성 사전 — **영문 사전과 같은 척도로** 국내 뉴스를 채점한다.

왜 KR-FinBert 만으로는 부족한가
===============================
교차언어 전이 모델(`newsxfer`)은 xforecast 미국 뉴스 47만 건을
**사전 방식**(`lexicon.py`)으로 채점한 피처로 학습했다. 그런데 국내 뉴스는
KR-FinBert 로 채점해서 넣고 있었다.

    학습:  영문 뉴스 → LM 사전       → polarity ∈ [-1, +1], 평활항 SMOOTH=3
    적용:  국내 뉴스 → KR-FinBert    → softmax 확률 기반, 분포가 전혀 다름

**같은 이름의 열에 서로 다른 척도의 값이 들어간 것이다.** 사전은 근거 단어가
하나뿐이면 평활항 때문에 ±0.25 근처에 머무는데, BERT 는 확신하면 0.99 를
뱉는다. 미국에서 배운 임계값이 한국에 맞을 리가 없다.

그래서 **영문 사전의 어휘를 한국어로 옮겨** 같은 방식으로 채점한다.
이러면 학습 분포와 적용 분포가 맞는다. KR-FinBert 는 없애지 않고 남겨 둔다 —
사용자에게 읽어 줄 문장 톤에는 그쪽이 낫다.

번역이 아니라 대응
------------------
단어를 사전적으로 옮기지 않았다. **같은 사건을 가리키는 국내 표현**으로
대응시켰다.

    beat / surpass  →  상회 · 웃돌 · 어닝서프라이즈
    miss / shortfall→  하회 · 밑돌 · 어닝쇼크
    upgrade         →  목표주가 상향 · 투자의견 상향
    guidance cut    →  가이던스 하향 · 전망 하향

한국어는 교착어라 어미가 붙는다("상승했다", "상승세", "상승폭"). 그래서
토큰 일치가 아니라 **부분 문자열 포함**으로 센다. 어간만 등록하면 활용형이
모두 걸린다.

부정 처리
---------
"늘지 않았다", "회복 못 했다" 처럼 **뒤에** 부정어가 온다. 영어와 반대다.
범위는 글자 수가 아니라 **어절**로 잡는다 — 글자 수로 자르면
"실적 개선 차질 없이"가 부정으로 뒤집힌다 (`_has_negator_after` 주석).

모호한 단일어는 넣지 않는다
---------------------------
"증가"·"확대"만 등록했더니 "비용만 증가", "적자 확대"가 긍정으로 잡혔다.
**무엇이** 늘었는지가 부호를 정하므로 복합어로 등록한다.

검증: `python tests/test_lexicon_ko.py` (11/11)
"""

from __future__ import annotations

import re

SMOOTH = 3.0        # lexicon.py 와 **같은 값**이어야 척도가 맞는다
NEG_AFTER = 12      # 매칭어 뒤 이 글자 수 안에 부정어가 있으면 뒤집는다

# 어절 단위로 보므로 "못" 하나만 있어도 안전하다 (아래 _has_negator_after).
