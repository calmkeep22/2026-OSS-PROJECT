UNCERTAIN = (
    "가능성", "전망", "예상", "추정", "관측", "검토", "저울질",
    "불확실", "변수", "관망", "혼조", "엇갈", "눈치", "주춤",
    "일 듯", "할 듯", "될 듯", "듯한", "인 듯",
)

_WS = re.compile(r"\s+")


def _has_negator_after(text: str, end: int) -> bool:
    """
    매칭어 **바로 뒤 어절 하나** 안에 부정어가 있는가.

    ⚠️ 글자 수로 자르면 안 된다.
    처음엔 "뒤 12글자"로 봤는데, 그러면 이런 게 뒤집힌다.

        "실적 개선 차질 없이 진행"
                ↑ 개선(긍정)      ↑ 12글자 안에 '없' → 부정으로 뒤집힘 ❌

    "차질 없이"는 오히려 긍정인데 정반대로 읽는다. 한국어의 부정은 **바로
    앞 요소에만** 걸리므로, 매칭어가 속한 어절의 나머지와 그다음 어절
    하나까지만 본다.

        "상회하지 않았다"   → 같은 어절 '하지' + 다음 어절 '않았다'  → 뒤집음 ✅
        "회복 못 했다"      → 다음 어절 '못'                        → 뒤집음 ✅
        "성장 없이"         → 다음 어절 '없이'                      → 뒤집음 ✅
        "개선 차질 없이"    → 다음 어절 '차질' 뿐                   → 안 뒤집음 ✅
    """
    tail = text[end:end + NEG_AFTER * 2]
    parts = tail.split(" ", 2)
    scope = " ".join(parts[:2])          # 같은 어절의 나머지 + 다음 어절 하나
    return any(g in scope for g in NEGATORS)


def _count(text: str, terms: tuple[str, ...]) -> tuple[int, int]:
    """
    (뒤집히지 않은 매칭 수, 뒤집힌 매칭 수).

    긴 표현을 먼저 세고 그 자리를 지워, "목표주가 상향"이 "상향"으로 다시
    세이는 이중 계수를 막는다.
    """
    plain = flipped = 0
    buf = text
    for t in sorted(terms, key=len, reverse=True):
        start = 0
        while True:
            i = buf.find(t, start)
            if i < 0:
                break
            if _has_negator_after(buf, i + len(t)):
                flipped += 1
            else:
                plain += 1
            buf = buf[:i] + " " * len(t) + buf[i + len(t):]
            start = i + len(t)
    return plain, flipped


def score(text: str) -> dict[str, float]:
    """
    국문 금융 텍스트 → 극성·불확실성. **반환 스키마는 `lexicon.score` 와 같다.**

    같은 키·같은 평활항을 쓰는 것이 이 모듈의 존재 이유다. 하나라도 다르면
    전이 모델이 학습한 것과 다른 값을 받게 된다.
    """
    empty = {"polarity": 0.0, "pos_ratio": 0.0, "neg_ratio": 0.0,
             "uncertainty": 0.0, "n_words": 0.0}
    if not text:
        return empty
    t = _WS.sub(" ", text)
    n = len(t.split())
    if not n:
        return empty

    p_plain, p_flip = _count(t, POSITIVE)
    n_plain, n_flip = _count(t, NEGATIVE)
    u_plain, _u_flip = _count(t, UNCERTAIN)

    # 부정된 긍정어는 부정 쪽으로, 부정된 부정어는 긍정 쪽으로 넘어간다.
    pos = p_plain + n_flip
    neg = n_plain + p_flip

    return {"polarity": (pos - neg) / (pos + neg + SMOOTH),
            "pos_ratio": pos / n,
            "neg_ratio": neg / n,
            "uncertainty": u_plain / n,
            "n_words": float(n)}


def score_many(texts) -> list[dict[str, float]]:
    """여러 건. 문자열 검색이라 수만 건도 몇 초면 끝난다."""
    return [score(t if isinstance(t, str) else "") for t in texts]


def vocab_size() -> dict[str, int]:
    """사전 규모. 리포트에 싣는다."""
    return {"긍정": len(POSITIVE), "부정": len(NEGATIVE),
            "불확실": len(UNCERTAIN)}
